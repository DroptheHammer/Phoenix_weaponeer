// Regenerates src-tauri/src/parsers/airfields_data.rs from pydcs.
//
// DCS numbers airfields per theater, and a route point's `airdromeId` is that
// number. pydcs reads the ids, names and positions out of DCS itself, so its
// `dcs/terrain/<map>/airports.py` files are the source. The commit is pinned so
// a regeneration is a deliberate, reviewable bump rather than whatever pydcs
// master happens to be that day.
//
// Run: npm run gen-airfields, then cargo test. The fixture test in
// `airfields.rs` checks the Sinai and Nevada ids against real missions.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const PYDCS_SHA = '55dc18adbd6907ea17d87de559445c4f9bc39146';

// [our normalized theater name, pydcs terrain directory]. Iraq and Afghanistan
// have no pydcs terrain, so they are absent and their points stay unnamed.
const THEATERS = [
  ['caucasus', 'caucasus'],
  ['nevada', 'nevada'],
  ['syria', 'syria'],
  ['persian_gulf', 'persiangulf'],
  ['normandy', 'normandy'],
  ['marianas', 'marianaislands'],
  ['south_atlantic', 'falklands'],
  ['germany_cw', 'germany'],
  ['sinai', 'sinai'],
  ['kola', 'kola'],
  ['channel', 'thechannel'],
];

const OUT = fileURLToPath(new URL('../src-tauri/src/parsers/airfields_data.rs', import.meta.url));

/** Pulls `id`, `name` and the constructor position out of each airport class. */
function parseAirports(source, dir) {
  const airports = [];
  let current = null;
  for (const line of source.split('\n')) {
    let match;
    if ((match = line.match(/^\s+id = (\d+)\s*$/))) {
      current = { id: Number(match[1]) };
      airports.push(current);
    } else if (current && current.name === undefined && (match = line.match(/^\s+name = "((?:[^"\\]|\\.)*)"\s*$/))) {
      current.name = match[1].replace(/\\(.)/g, '$1');
    } else if (current && current.x === undefined && (match = line.match(/super\(\)\.__init__\(mapping\.Point\((-?[\d.]+), (-?[\d.]+), terrain\)/))) {
      current.x = Number(match[1]);
      current.y = Number(match[2]);
    }
  }

  if (airports.length === 0) throw new Error(`${dir}: no airports parsed`);
  const seen = new Set();
  for (const airport of airports) {
    if (!airport.name || !Number.isFinite(airport.x) || !Number.isFinite(airport.y)) {
      throw new Error(`${dir}: airport id ${airport.id} is missing a name or position`);
    }
    if (seen.has(airport.id)) throw new Error(`${dir}: duplicate airport id ${airport.id}`);
    seen.add(airport.id);
  }
  return airports.sort((a, b) => a.id - b.id);
}

const rustString = (text) => text.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

const rustFloat = (value) => {
  const text = Number.isInteger(value) ? `${value}.0` : String(value);
  if (text.includes('e')) throw new Error(`unexpected exponent in ${text}`);
  return text;
};

const lines = [
  '//! GENERATED by `scripts/gen-airfields.mjs` from pydcs',
  `//! ${PYDCS_SHA}. Do not edit by hand; re-run \`npm run gen-airfields\`.`,
  '',
  'use super::airfields::Airfield;',
  '',
  '#[rustfmt::skip]',
  'pub static AIRFIELDS: &[(&str, &[Airfield])] = &[',
];

for (const [theater, dir] of THEATERS) {
  const url = `https://raw.githubusercontent.com/pydcs/dcs/${PYDCS_SHA}/dcs/terrain/${dir}/airports.py`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${dir}: ${response.status} fetching ${url}`);
  const airports = parseAirports(await response.text(), dir);
  console.log(`${theater.padEnd(16)} ${airports.length} airfields`);

  lines.push(`    ("${theater}", &[`);
  for (const airport of airports) {
    lines.push(
      `        Airfield { id: ${airport.id}, name: "${rustString(airport.name)}", x: ${rustFloat(airport.x)}, y: ${rustFloat(airport.y)} },`,
    );
  }
  lines.push('    ]),');
}
lines.push('];', '');

writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${OUT}`);
